/**
 * Writes dist/_redirects after the Vite build.
 *
 * Two rules matter, and the order matters:
 *
 *   1. /api/*  proxied to the deployed .NET API, when API_PROXY_TARGET is set.
 *      Proxying keeps the browser on one origin, so there is no CORS to
 *      configure and no provider host baked into the bundle.
 *   2. /*      falls back to index.html so client-side routes such as
 *      /careers/ai-solutions-architect resolve instead of returning 404.
 *
 * This is generated rather than committed because the proxy target differs per
 * environment, and netlify.toml cannot interpolate environment variables.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'dist/_redirects');

// Accept either name: API_PROXY_TARGET reads better in Netlify's UI, but a
// VITE_-prefixed variable is what people reach for first.
const raw = process.env.API_PROXY_TARGET ?? process.env.VITE_API_PROXY_TARGET ?? '';
const target = raw.trim().replace(/\/+$/, '');

const lines = ['# Generated by scripts/generate-redirects.mjs — do not edit by hand.', ''];

if (target) {
  if (!/^https?:\/\//.test(target)) {
    console.error(
      `\n[redirects] API_PROXY_TARGET must be an absolute http(s) URL, got "${raw}".\n`,
    );
    process.exit(1);
  }
  lines.push('# Same-origin proxy to the deployed API, so the SPA needs no CORS grant.');
  lines.push(`/api/*  ${target}/api/:splat  200`);
  lines.push('');
} else {
  lines.push('# No API_PROXY_TARGET set: the SPA will call whatever VITE_API_BASE_URL');
  lines.push('# points at, and sign-in fails with a clear message if nothing is there.');
  lines.push('');
}

lines.push('# SPA fallback — must stay last so it cannot swallow the API rule.');
lines.push('/*  /index.html  200');
lines.push('');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'), 'utf8');

console.log(
  target
    ? `[redirects] /api/* -> ${target}/api/:splat, SPA fallback written.`
    : '[redirects] SPA fallback written. No API proxy configured.',
);
